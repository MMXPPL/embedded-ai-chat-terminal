// 生成 pinyin_data.h：拼音 -> 汉字候选表（按常用度排序）
const fs = require("fs");

// 1) 解析 pinyin.txt：U+XXXX: pinyin1,pinyin2  # comment
const raw = fs.readFileSync(".tmpchk/pinyin.txt", "utf8");
const syllableMap = new Map(); // syllable -> Set<char>
function untoned(s) {
  s = s.replace(/[üǖǘǚǜÜǙǛǗ]/g, "v").replace(/ê/g, "e");
  return s.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
}
for (const line of raw.split("\n")) {
  const m = line.match(/^U\+([0-9A-F]{4,5}):\s*([^#]+)/);
  if (!m) continue;
  const cp = parseInt(m[1], 16);
  // 只保留字体（0x4E00-0x9FA5）覆盖的汉字
  if (cp < 0x4E00 || cp > 0x9FA5) continue;
  const ch = String.fromCodePoint(cp);
  const readings = m[2].split(",").map(x => untoned(x.trim())).filter(x => /^[a-z]+$/.test(x));
  for (const py of readings) {
    if (!syllableMap.has(py)) syllableMap.set(py, new Set());
    syllableMap.get(py).add(ch);
  }
}

// 2) 常用字表顺序：序号 汉字 频率
let html = fs.readFileSync(".tmpchk/changyong_utf8.txt", "utf8");
html = html.replace(/<[^>]*>/g, " ");
const rank = new Map(); // char -> rank (1=最常用)
for (const m of html.matchAll(/\s(\d+)\s+([\u4e00-\u9fa5])\s+(\d+)/g)) {
  if (!rank.has(m[2])) rank.set(m[2], parseInt(m[1], 10));
}

// 3) 组装输出（拼音按字母序，候选按常用度，未知字按 unicode 排最后）
const entries = [];
for (const [py, set] of syllableMap) {
  const chars = [...set].sort((a, b) => {
    const ra = rank.get(a) || 4000;
    const rb = rank.get(b) || 4000;
    return ra !== rb ? ra - rb : a.codePointAt(0) - b.codePointAt(0);
  });
  entries.push({ py, hz: chars.join("") });
}
entries.sort((a, b) => a.py < b.py ? -1 : a.py > b.py ? 1 : 0);

// 4) 输出头文件
let out = `/* Auto-generated by pinyin generator. Do not edit. */
/* 拼音 -> 汉字候选表：候选按现代汉语常用字表排序（常用字在前） */
#ifndef PINYIN_DATA_H
#define PINYIN_DATA_H

typedef struct { const char *py; const char *hz; } py_entry_t;

static const py_entry_t py_table[] = {
`;
for (const e of entries) {
  out += `    {"${e.py}", "${e.hz}"},\n`;
}
out += `};

#define PY_TABLE_LEN (sizeof(py_table) / sizeof(py_table[0]))

#endif /* PINYIN_DATA_H */
`;
fs.writeFileSync("D:/VM-share/lv_port_linux_v8.2/my_data/pinyin_data.h", out);
console.log("音节数:", entries.length, "候选字符总数:", entries.reduce((s, e) => s + e.hz.length, 0));
// 抽查常用音节
for (const py of ["ni", "hao", "wo", "shi", "de", "ma", "bang"]) {
  const e = entries.find(x => x.py === py);
  console.log(py, "=>", e ? e.hz.slice(0, 12) : "(无)");
}
